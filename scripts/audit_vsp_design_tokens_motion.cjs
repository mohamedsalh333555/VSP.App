#!/usr/bin/env node
'use strict';

/**
 * Read-only inventory of source styling and motion usage. This is NOT a linter:
 * a literal is a review candidate, not evidence of a visual regression.
 *
 * Example: node scripts/audit_vsp_design_tokens_motion.cjs --markdown
 */
const fs = require('node:fs');
const path = require('node:path');

const SOURCE_PATTERNS = {
  colorToken: /\b(?:VSPColors|VSPDSColors|VSPDSSemanticColors)\.\w+/g,
  directMaterialColor: /\bColors\.\w+/g,
  literalColor: /\bColor\s*\(\s*0x[\da-fA-F]{6,8}\s*\)/g,
  spacingToken: /\b(?:VSPSpacing|VSPDSSpacing)\.\w+/g,
  radiusToken: /\b(?:VSPRadius|VSPDSRadius)\.\w+/g,
  textFontSize: /\bfontSize\s*:\s*(?:\d+(?:\.\d+)?)/g,
  textFontFamily: /\bfontFamily\s*:\s*['"][^'"]+['"]/g,
  edgeInsets: /\bEdgeInsets(?:Directional)?\.(?:all|only|symmetric|fromLTRB|fromSTEB)/g,
  sizeGap: /\bSizedBox\s*\(/g,
  motionToken: /\bVSPDSMotion\.\w+/g,
  animatedWidget: /\b(?:AnimatedContainer|AnimatedOpacity|AnimatedSwitcher|AnimatedSize|AnimatedScale|AnimatedPositioned|AnimatedAlign|AnimatedRotation|AnimatedSlide|AnimatedCrossFade|AnimatedPadding|AnimatedTheme|AnimatedDefaultTextStyle|AnimatedPhysicalModel|AnimatedList|TweenAnimationBuilder|AnimationController|CurvedAnimation|FadeTransition|SlideTransition|ScaleTransition|SizeTransition|RotationTransition|PositionedTransition|AlignTransition|Hero)\b/g,
  routeTransition: /\b(?:PageRouteBuilder|MaterialPageRoute|CupertinoPageRoute|CustomTransitionPage|NoTransitionPage)\b/g,
  explicitMotionDuration: /\bDuration\s*\(\s*(?:milliseconds|microseconds|seconds)\s*:/g,
  reduceMotionGate: /\b(?:disableAnimationsOf|accessibleNavigationOf|MediaQueryData\s*\.\s*disableAnimations)\b/g,
};

const CATEGORIES = Object.freeze(Object.keys(SOURCE_PATTERNS));

function walkDartFiles(root) {
  const output = [];
  function visit(dir) {
    for (const item of fs.readdirSync(dir, { withFileTypes: true }).sort(
      (a, b) => a.name.localeCompare(b.name, 'en'),
    )) {
      const full = path.join(dir, item.name);
      if (item.isDirectory()) {
        if (!['.dart_tool', 'generated', '.git', 'build'].includes(item.name)) {
          visit(full);
        }
      } else if (item.isFile() && item.name.endsWith('.dart') &&
                 !/(?:\.g|\.freezed|\.gr)\.dart$/.test(item.name)) {
        output.push(full);
      }
    }
  }
  visit(root);
  return output.sort();
}

function auditSource(root) {
  const absolute = path.resolve(root);
  if (!fs.existsSync(absolute) || !fs.statSync(absolute).isDirectory()) {
    throw new Error('Source directory does not exist');
  }
  const files = walkDartFiles(absolute);
  const buckets = Object.fromEntries(
    CATEGORIES.map((key) => [key, { matches: 0, files: 0, samples: [] }]),
  );
  for (const full of files) {
    const text = fs.readFileSync(full, 'utf8');
    const lines = text.split(/\r?\n/);
    const relative = path.relative(absolute, full).replaceAll(path.sep, '/');
    const perFile = new Set();
    lines.forEach((line, n) => {
      // Simple comments are ignored. This is a syntactic inventory, not an AST
      // parser; strings, multiline comments and generated code remain limits.
      if (line.trimStart().startsWith('//')) return;
      for (const [key, expression] of Object.entries(SOURCE_PATTERNS)) {
        const matches = line.match(expression);
        if (!matches) continue;
        buckets[key].matches += matches.length;
        perFile.add(key);
        if (buckets[key].samples.length < 12) {
          buckets[key].samples.push({
            path: relative,
            line: n + 1,
            example: matches.slice(0, 3).join(', '),
          });
        }
      }
    });
    for (const key of perFile) buckets[key].files++;
  }
  return {
    sourceRoot: path.basename(absolute),
    totalDartFiles: files.length,
    groups: buckets,
    notes: [
      'Automated source-only inventory: counts are approximate and are not defect findings.',
      'Generated .g.dart/.freezed.dart/.gr.dart files and the generated/ directory are excluded.',
      'Inline expressions in code strings or multi-line comments may be counted; verify before remediation.',
      'Navigation routes are counted as transition review points; default routes are not necessarily custom animations.',
      'Animation inventory does not prove runtime reduced-motion support; Android device testing remains open.',
    ],
  };
}

function toMarkdown(result) {
  const lines = [
    '# VSP — Source design tokens and motion inventory',
    '',
    'Generated by \`scripts/audit_vsp_design_tokens_motion.cjs\` (read-only).',
    '',
    `Inspected ${result.totalDartFiles} non-generated Dart files under \`${result.sourceRoot}/\`.`,
    '',
    '| Category | References | Files |',
    '| --- | ---: | ---: |',
  ];
  for (const category of CATEGORIES) {
    const group = result.groups[category];
    lines.push(`| \`${category}\` | ${group.matches} | ${group.files} |`);
  }
  for (const key of CATEGORIES) {
    const samples = result.groups[key].samples;
    if (!samples.length) continue;
    lines.push('', `## ${key}: representative source positions`, '');
    for (const hit of samples) {
      lines.push(`- \`${hit.path}:${hit.line}\` — \`${hit.example}\``);
    }
  }
  lines.push('', '## Limitations', '', ...result.notes.map(x => '- ' + x), '');
  return lines.join('\n');
}

if (require.main === module) {
  const rootFlag = process.argv.indexOf('--root');
  const root = rootFlag !== -1 ? process.argv[rootFlag + 1] : 'lib';
  const output = auditSource(root);
  process.stdout.write(
    process.argv.includes('--json') ?
      JSON.stringify(output, null, 2) + '\n' : toMarkdown(output) + '\n',
  );
}
module.exports = { SOURCE_PATTERNS, walkDartFiles, auditSource, toMarkdown };
